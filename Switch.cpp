#include <iostream>
using namespace std;
int main() {
    int number = 7;
   
    switch(number)
    {
        case 1:
        cout << "19 is Monday";
        break;

        case 2:
        cout << "20 is Tuesday";

        case 3:
        cout << " 21 is Wednesday";

        case 4:
        cout << "22 is Thursday";

        case 5:
        cout << "23 is Friday";

        case 6:
        cout << "24 is Saturday";

        case 7:
        cout << "25 is Sunday";
    }


    return 0;
}